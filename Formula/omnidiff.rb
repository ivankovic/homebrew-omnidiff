# The Homebrew formula for the tap at github.com/ivankovic/homebrew-omnidiff, as a template:
# scripts/render_homebrew_formula.py fills the version and the checksums from a release's
# SHA256SUMS.txt, and release.yml pushes the result to the tap. The installed binary is the same
# attested release asset every other route ships, so `brew install` takes seconds instead of the
# ten-minute grammar-and-LTO compile a build-from-source formula would run on every machine.
class Omnidiff < Formula
  desc "Fast, robust, accurate content-aware diffing"
  homepage "https://github.com/ivankovic/omnidiff"
  version "0.3.0"
  license "AGPL-3.0-only"

  on_macos do
    on_arm do
      url "https://github.com/ivankovic/omnidiff/releases/download/v0.3.0/omnidiff-aarch64-apple-darwin.tar.gz"
      sha256 "6b6d0367b9ca4f1485f2b57da40d42d7190def1ca5bf56b2fef01f12a388bc20"
    end
    on_intel do
      url "https://github.com/ivankovic/omnidiff/releases/download/v0.3.0/omnidiff-x86_64-apple-darwin.tar.gz"
      sha256 "c45e88a96089139e2c43b2a1d6a70c9ee9680e0c720a94eddd2327f57159fc5a"
    end
  end

  # The static musl binaries: Homebrew on Linux runs on any distribution, and these run on any
  # glibc, or none.
  on_linux do
    on_arm do
      url "https://github.com/ivankovic/omnidiff/releases/download/v0.3.0/omnidiff-aarch64-unknown-linux-musl.tar.gz"
      sha256 "17c9c9b986d5b495a50ed0e088f98db7a817648ea0582140f8f76c68a73aba51"
    end
    on_intel do
      url "https://github.com/ivankovic/omnidiff/releases/download/v0.3.0/omnidiff-x86_64-unknown-linux-musl.tar.gz"
      sha256 "c85ec5c2f931a52c77aba34211b3c5de377112e8098bdf02a016503856ada1ae"
    end
  end

  def install
    bin.install "omnidiff"
    # Generated by the binary just installed, from the same clap definition as --help.
    (man1/"omnidiff.1").write Utils.safe_popen_read(bin/"omnidiff", "util", "man")
    generate_completions_from_executable(bin/"omnidiff", "util", "completions")
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/omnidiff --version")
    (testpath/"before.py").write "def f(x):\n    return x + 1\n"
    (testpath/"after.py").write "def f(x):\n    return x + 2\n"
    output = shell_output("#{bin}/omnidiff --headless before.py after.py")
    assert_match "x + 2", output
  end
end
